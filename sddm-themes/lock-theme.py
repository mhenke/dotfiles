#!/usr/bin/env python3
"""Render the Hyprlock include for the current wallpaper from the SDDM catalog.

Usage: lock-theme.py WALLPAPER_PATH

The single source of truth is the theme-*.conf whose General.Background
basename matches the wallpaper filename: [General] supplies the welcome header,
and [Lock] supplies colors and placement. Unlisted wallpapers use
theme-staircase.conf. Bad known data leaves the previous include untouched.
"""
import math
import os
import re
import sys
import tempfile
from configparser import ConfigParser, Error as ConfigError
from html import escape
from pathlib import Path

CATALOG = Path(__file__).resolve().parent / "simple-sddm" / "configs"
FALLBACK_THEME = "theme-staircase.conf"
DEST_RELATIVE = Path(".config/hypr/UserConfigs/hyprlock-theme.conf")
TEXT_COLOR = "rgb(FFF5E9)"
DATE_Y_OFFSET = 13.333333
HEX_COLOR = re.compile(r"#?([0-9A-Fa-f]{6})\Z")

MARKUP = (
    '<span foreground="##{hour}">%H</span>'
    '<span size="15pt"> </span>'
    '<span foreground="##{minute}">%M</span>'
    '<span size="55pt"> </span>'
    '<span foreground="##{second}" size="70pt" rise="30720">%S</span>'
)


class ThemeError(Exception):
    pass


def parse(path):
    parser = ConfigParser(interpolation=None)
    parser.optionxform = str
    try:
        with open(path, encoding="utf-8") as handle:
            parser.read_file(handle)
    except (OSError, UnicodeDecodeError, ConfigError) as error:
        raise ThemeError(f"cannot read {path}: {error}") from error
    return parser


def unquote(value):
    value = value.strip()
    if len(value) > 1 and value[0] == value[-1] and value[0] in "\"'":
        value = value[1:-1]
    return value


def background_of(parser):
    try:
        return unquote(parser["General"]["Background"])
    except KeyError as error:
        raise ThemeError(f"missing General Background: {error}") from error


def select_theme(wallpaper_path):
    # Resolve first: pointers like wallpaper_effects/.wallpaper_current carry no
    # image identity until followed, and self-links would loop the match.
    wanted = Path(wallpaper_path).resolve(strict=False).name
    for path in sorted(CATALOG.glob("theme-*.conf")):
        try:
            if os.path.basename(background_of(parse(path))) == wanted:
                return path
        except ThemeError:
            continue  # a broken catalog file can never match; fallback handles the rest
    return CATALOG / FALLBACK_THEME


def lock_value(lock, key):
    try:
        return lock[key]
    except KeyError as error:
        raise ThemeError(f"[Lock] missing {key}: {error}") from error


def color(lock, key):
    match = HEX_COLOR.match(unquote(lock_value(lock, key)))
    if not match:
        raise ThemeError(f"{key} is not a #RRGGBB color: {lock_value(lock, key)!r}")
    return match.group(1)


def percent(lock, key):
    try:
        value = float(unquote(lock_value(lock, key)))
    except ValueError as error:
        raise ThemeError(f"{key} is not a number: {lock_value(lock, key)!r}") from error
    if not math.isfinite(value) or not 0.0 <= value <= 100.0:
        raise ThemeError(f"{key} out of the 0..100 range: {lock_value(lock, key)!r}")
    return value


def fmt(value):
    return f"{value:.6f}".rstrip("0").rstrip(".")


def render(theme_path, theme):
    try:
        lock = theme["Lock"]
    except KeyError as error:
        raise ThemeError(f"{theme_path.name} has no [Lock] section: {error}") from error
    hour = color(lock, "HourColor")
    minute = color(lock, "MinuteColor")
    second = color(lock, "SecondColor")
    clock_x, clock_y, unlock_x = (percent(lock, k) for k in ("ClockX", "ClockY", "UnlockX"))
    x = fmt(clock_x - 50.0)
    y = fmt(50.0 - clock_y)
    text = f"""# Generated by sddm-themes/lock-theme.py from {theme_path.name} [General]/[Lock] — do not edit.
$lockTextColor = {TEXT_COLOR}
$lockAccentColor = rgb({minute})
$lockDatePosition = {x}%,{fmt(50.0 - clock_y - DATE_Y_OFFSET)}%
$lockUserPosition = {fmt(unlock_x - 50.0)}%,200
$lockInputPosition = {fmt(unlock_x - 50.0)}%,100

# One label, one date call: the gaps are markup, so hours and minutes cannot drift apart.
label {{
    monitor =
    text = cmd[update:1000] date +'{MARKUP.format(hour=hour, minute=minute, second=second)}'
    color = $lockTextColor
    font_size = 150
    font_family = JetBrainsMono Nerd Font ExtraBold
    position = {x}%,{y}%
    halign = center
    valign = center
    shadow_passes = 1
    shadow_size = 3
    shadow_color = rgb(000000)
}}
"""
    header = unquote(theme.get("General", "HeaderText", fallback=""))
    if header:
        # Keep catalog copy literal through Hyprlang variables/comments and Pango markup.
        header = escape(header).replace("$", "&#36;").replace("\n", "&#10;").replace("\r", "&#13;").replace("#", "##")
        text += f"""
label {{
    monitor =
    text = <span>{header}</span>
    color = $lockTextColor
    font_size = 24
    font_family = JetBrainsMono Nerd Font ExtraBold
    position = {fmt(unlock_x - 50.0)}%,300
    halign = center
    valign = bottom
    shadow_passes = 1
    shadow_size = 3
    shadow_color = rgb(000000)
}}
"""
    return text


def write_include(text):
    dest = Path.home() / DEST_RELATIVE
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=dest.parent, prefix=".hyprlock-theme.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(tmp, dest)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def main(argv):
    if len(argv) != 2:
        print("usage: lock-theme.py WALLPAPER_PATH", file=sys.stderr)
        return 1
    theme_path = select_theme(argv[1])
    text = render(theme_path, parse(theme_path))
    write_include(text)
    print(f"lock theme: {theme_path.name} -> {Path.home() / DEST_RELATIVE}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv))
    except (ThemeError, OSError) as error:
        print(f"lock-theme: {error}", file=sys.stderr)
        sys.exit(1)
